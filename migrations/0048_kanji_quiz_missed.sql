-- 漢字クイズの時間切れを記録し、1配信で何回時間切れになったら配信を止めるかを設定にする
--
-- 日時は 0001〜0047 と同じく UTC の ISO 8601（例: 2026-10-27T12:00:00.000Z）の文字列で持つ。
-- 適用方法は docs/guide/stats.md を参照。
--
-- 受付の締め切りに正解者がいなければ、Worker が missed_at に時間切れを確かめた時刻を書く（worker/kanji-quiz-store.ts の missKanjiQuiz）。
-- 「まだ正解者がいない・まだ書かれていない行」だけを書き換える1つの文で行うので、正解者の記録（answerKanjiQuiz）とはどちらか一方しか通らない。
-- 同じ配信の時間切れの数（試し再生を除く）が、管理画面で決めた回数（KV の kanji-quiz-miss-limit）に届いた出題でだけ、停止を始める（stop_at）。
-- 届かなければ止めずに、合成ページへあと何回で配信が終わるかを知らせる。
--
-- この列を足す前の行は NULL のまま残す（前の配信の時間切れは数えない。配信中に適用しても、その配信のそれまでの時間切れは数えない）。
ALTER TABLE kanji_quizzes ADD COLUMN missed_at TEXT;
